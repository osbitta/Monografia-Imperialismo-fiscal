function getMatchingMecanismos(text, paraId) {
    if (!window.mecanismosData) return [];

    // Prioridade máxima: Mapeamento canônico exato pelo ID do parágrafo no Apêndice A
    if (paraId && relatorioMecanismosMap && relatorioMecanismosMap[paraId]) {
        const targetNums = relatorioMecanismosMap[paraId].map(n => String(n));
        return window.mecanismosData.filter(m => targetNums.includes(String(m.numero)));
    }

    // Fallback: Busca semântica por palavras-chave
    if (!text) return [];
    const matched = [];
    for (const m of window.mecanismosData) {
        let isMatch = false;
        for (const kw of m.keywords) {
            const escaped = kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
            const flags = kw === kw.toUpperCase() && kw.length <= 5 ? '' : 'i';
            const regex = new RegExp(`(?<![A-Za-z0-9À-ÿ])${escaped}(?![A-Za-z0-9À-ÿ])`, flags);
            if (regex.test(text)) {
                isMatch = true;
                break;
            }
        }
        if (isMatch) {
            matched.push(m);
        }
    }
    return matched;
}

