function getMatchingTermos(text) {
    if (!text || !window.termosData) return [];
    const matched = [];
    for (const item of window.termosData) {
        let isMatch = false;
        for (const variant of item.sinonimos) {
            const escaped = variant.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
            // If variant is all uppercase, match case-sensitively; otherwise case-insensitively
            const flags = variant === variant.toUpperCase() && variant.length <= 5 ? '' : 'i';
            const regex = new RegExp(`(?<![A-Za-z0-9À-ÿ])${escaped}(?![A-Za-z0-9À-ÿ])`, flags);
            if (regex.test(text)) {
                isMatch = true;
                break;
            }
        }
        if (isMatch) {
            matched.push(item);
        }
    }
    return matched;
}

