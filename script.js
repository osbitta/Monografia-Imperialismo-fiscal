function getCommentsForPara(paraId) {
    if (!window.siteComments || !paraId) return [];
    const cleanId = String(paraId).trim().toUpperCase();
    const numOnly = cleanId.replace(/[^0-9]/g, '');
    return window.siteComments.filter(c => {
        if (!c || !c.comentario || !c.paragrafo) return false;
        const cPara = String(c.paragrafo).trim().toUpperCase();
        if (cPara === cleanId) return true;
        if (numOnly && cPara.replace(/[^0-9]/g, '') === numOnly) return true;
        return false;
    });
}

